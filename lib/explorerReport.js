import { jsPDF } from "jspdf";
import { buildRecommendations } from "./recommendations.js";
import { fromSession } from "./scoringV2/fromSession.js";
import { getCourseData, schoolLabel } from "./courseDataV2.js";
import { cardInfoFor } from "./courseSearch.js";
import { explainMatch, evidenceLines } from "./explainMatch.js";
import { ROUTE_LABELS } from "./routeResolution.js";
import items from "../data/v2/items.json" with { type: "json" };
import { translate } from "./i18n/translate.js";

const COLORS = { navy: [27,42,74], gold: [212,160,23], beige: [245,236,215], muted: [91,101,122] };
const DISCLAIMER = "This is a guidance tool, not a final decision - talk to your guidance counselor about what's right for you.";
export const REPORT_GENERATOR_LABEL = "Generated by CAREER COMPASS: A Web-based Decision Support System for Senior High School Career Guidance.";
export const reportGenerationDate = (date = new Date()) => new Intl.DateTimeFormat("en-PH", { year: "numeric", month: "long", day: "numeric", timeZone: "Asia/Manila" }).format(date);
// User-approved PDF-only currency substitution. Comparison retains source strings.
export const printableText = text => String(text).replace(/₱/g, "PHP ").replace(/—/g, "-").replace(/[‘’]/g, "'").replace(/[“”]/g, '"');
const label = (bank,id) => bank.find(item => item.id === id)?.text || "Not sure yet";
export function buildExplorerReport(session, language = "en") {
  const t = value => translate(value, language);
  const result = buildRecommendations(session);
  if (!result.ok) return { ok: false, errors: result.errors };
  const { answers } = fromSession(session);
  const topCourses = result.ranked.slice(0,5).map(({id,name,group,rank}) => {
    const course = getCourseData(id), remaining = [...course.schools], schools = [];
    for (let index = 0; index < 2 && remaining.length; index++) {
      const selected = cardInfoFor({ ...course, careers: course.careers.map(career => career.jobTitle), schools: remaining }).school;
      schools.push(schoolLabel(remaining.find(school => school.id === selected.id)));
      remaining.splice(remaining.findIndex(school => school.id === selected.id), 1);
    }
    return { id,name,group,rank, evidence: evidenceLines(explainMatch(id,answers)), careers: course.careers.slice(0,3).map(career => career.jobTitle), schools };
  });
  const profile = [
    ["Grade level", `Grade ${session.gradeLevel}`],
    ["Curriculum", ROUTE_LABELS[answers.route]],
    ...(answers.route === "old" ? [
      ["Strand", t(label(items.strands,answers.old.strand))],
      ["Subjects", answers.old.subjects.map(id=>t(label(items.oldSubjects,id))).join("; ")],
    ] : [
      ["Electives", answers.new.electives.length ? answers.new.electives.map(id=>label(items.electives,id)).join("; ") : t("Not sure yet / None")],
      ["Core subjects", answers.new.bestSubjects.map(id=>label(items.coreSubjects,id)).join("; ")],
    ]),
    ["GWA", String(answers.gwa)],
    ["Certificates & Achievements", answers.certificates.length ? answers.certificates.map(id=>t(label(items.certificates,id))).join("; ") : t("None yet")],
  ];
  return { ok: true, language: language === "fil" ? "fil" : "en", nickname: session.nickname?.trim() || "", date: session.reportDate || new Intl.DateTimeFormat("en-PH",{dateStyle:"long"}).format(new Date()), topCourses, profile: profile.map(([title,value])=>[t(title),t(value)]) };
}
export function createExplorerReport(report, { generatedAt = new Date() } = {}) {
  if (!report.ok) throw new Error("Complete the assessment before creating a report.");
  const doc = new jsPDF({unit:"mm",format:"a4"});
  const t = value => translate(value, report.language);
  const generationDate = reportGenerationDate(generatedAt);
  doc.setCreationDate(generatedAt);
  doc.setFont("helvetica", "normal"); doc.setFontSize(10);
  const footerLines = doc.splitTextToSize(printableText(t(REPORT_GENERATOR_LABEL)), 178);
  const footerLeading = 4.2, footerTop = 285 - (footerLines.length - 1) * footerLeading;
  const contentBottom = footerTop - 8;
  const nodes = [];
  const add = (value, options = {}) => nodes.push({ value: printableText(value), ...options });
  const heading = value => add(t(value), { bold: true, heading: true });
  add("CAREER COMPASS", { bold: true, title: true });
  add(t("Explorer Report"), { bold: true });
  if (report.nickname) add(t(`Prepared for ${report.nickname}`));
  for (const [title, value] of report.profile.slice(0,2)) add(`${title}: ${value}`);
  heading("Your Exploration Profile");
  for (const [title, value] of report.profile.slice(2)) add(`${title}: ${value}`);
  const evidence = [...new Set(report.topCourses.flatMap(course => course.evidence))];
  add(t("Supporting answers"), { bold: true });
  for (const line of evidence) add(`- ${t(line)}`);
  heading("Your Top Course Matches");
  for (const course of report.topCourses) {
    add(`${course.rank}. ${course.name}`, { bold: true, course: true });
    add(`${t("Careers")}: ${course.careers.join("; ")}`);
    add(`${t("Schools")}: ${course.schools.join("; ")}`);
  }
  add(t(DISCLAIMER), { note: true });
  add(t("School lists are not complete. Confirm programs, campus availability and admission requirements with the school."), { note: true });
  function layout(size) {
    let page = 1, y = 18;
    const measured = nodes.map(node => {
      const fontSize = node.title ? 16 : node.heading ? 13 : node.course ? 11 : size;
      doc.setFont("helvetica", node.bold ? "bold" : "normal"); doc.setFontSize(fontSize);
      const lines = doc.splitTextToSize(node.value, 178);
      const leading = fontSize * .3528 * 1.22;
      const gap = node.heading ? 4 : node.course || node.note ? 3 : 1.2;
      const height = lines.length * leading + gap;
      return { ...node, lines, fontSize, leading, height };
    });
    const lastCourse = measured.findLastIndex(node => node.course);
    return measured.map((node, index) => {
      const { lines, fontSize, leading, height } = node;
      // Keep each course together, and keep the two guidance notes with the last course.
      const following = node.course ? measured.slice(index + 1, index === lastCourse ? undefined : index + 3) : node.heading ? measured.slice(index + 1, index + 2) : [];
      const reserve = following.reduce((sum, entry) => sum + entry.height, 0);
      if (y + height + reserve > contentBottom) { page++; y = 18; }
      const placed = { ...node, lines, fontSize, leading, page, y };
      y += height;
      if (index === nodes.length - 1) placed.pages = page;
      return placed;
    });
  }
  let placed = layout(10.5);
  const compact = layout(10);
  if (compact.at(-1).pages < placed.at(-1).pages) placed = compact;
  if (placed.at(-1).pages > 2) throw new Error("Report exceeds the two-page layout. Review the content before downloading.");
  for (const node of placed) {
    while (doc.getNumberOfPages() < node.page) doc.addPage();
    doc.setPage(node.page); doc.setFont("helvetica", node.bold ? "bold" : "normal"); doc.setFontSize(node.fontSize);
    doc.setTextColor(...(node.note ? COLORS.muted : COLORS.navy));
    node.lines.forEach((line, index) => doc.text(line, node.title ? 105 : 16, node.y + index * node.leading, { align: node.title ? "center" : "left" }));
    if (node.heading) { doc.setDrawColor(...COLORS.gold); doc.line(16, node.y + node.lines.length * node.leading - 2, 194, node.y + node.lines.length * node.leading - 2); }
  }
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page); doc.setFont("helvetica", "normal"); doc.setFontSize(10); doc.setTextColor(...COLORS.muted);
    doc.setDrawColor(...COLORS.gold); doc.line(16, footerTop - 4, 194, footerTop - 4);
    footerLines.forEach((line, index) => doc.text(line, 105, footerTop + index * footerLeading, { align: "center" }));
    doc.text(`${t(`Generated on ${generationDate}`)} | ${t(`Career Compass | Page ${page} of ${pages}`)}`, 105, 291, { align: "center" });
  }
  return doc;
}
export async function downloadExplorerReport(report) { const doc=createExplorerReport(report);await doc.save("career-compass-explorer-report.pdf",{returnPromise:true}); }
export function printExplorerReport(report) { const doc=createExplorerReport(report);doc.autoPrint();window.open(doc.output("bloburl"),"_blank","noopener,noreferrer"); }
export { DISCLAIMER };

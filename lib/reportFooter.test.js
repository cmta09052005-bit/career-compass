import assert from "node:assert/strict";
import test from "node:test";
import cases from "../docs/qa/browser-sessions.json" with { type: "json" };
import { buildExplorerReport, createExplorerReport, reportGenerationDate } from "./explorerReport.js";

test("generation dates follow the Manila day boundary and never use a saved report date", context => {
  assert.equal(reportGenerationDate(new Date("2026-10-26T15:59:59Z")), "October 26, 2026");
  assert.equal(reportGenerationDate(new Date("2026-10-26T16:00:01Z")), "October 27, 2026");
  context.mock.timers.enable({ apis: ["Date"], now: new Date("2026-10-26T16:00:01Z") });
  const report = buildExplorerReport({ ...cases[0].session, reportDate: "January 1, 1990" });
  const doc = createExplorerReport(report);
  for (let page = 1; page <= doc.getNumberOfPages(); page++) {
    const content = doc.internal.pages[page].join("\n");
    assert.ok(content.includes("Generated by CAREER COMPASS:"));
    assert.ok(content.includes("October 27, 2026"));
    assert.ok(!content.includes("January 1, 1990"));
  }
});

test("each footer reserves room below content and the brand header is centered", () => {
  const doc = createExplorerReport(buildExplorerReport(cases[0].session), { generatedAt: new Date("2026-10-27T05:00:00Z") });
  const content = doc.internal.pages[1].join("\n");
  const brand = content.match(/([\d.]+) ([\d.]+) Td\n\(CAREER COMPASS\) Tj/);
  assert.ok(brand);
  doc.setFont("helvetica", "bold"); doc.setFontSize(16);
  const x = Number(brand[1]) / doc.internal.scaleFactor;
  assert.ok(Math.abs(x + doc.getTextWidth("CAREER COMPASS") / 2 - 105) < .5);
});

import { readdir, readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const version = (await readFile(path.join(root, ".next/BUILD_ID"), "utf8")).trim();
const prefix = `/offline-build/${version}`;
const destination = path.join(root, "public", prefix);
await mkdir(destination, { recursive: true });
async function files(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (await Promise.all(entries.map(entry => entry.isDirectory() ? files(path.join(directory, entry.name)) : path.join(directory, entry.name)))).flat();
}
const resources = [], routes = {};
async function add(file, url, key = url, type = "asset") {
  resources.push({ url, key, type, bytes: (await readFile(file)).length });
}
for (const file of await files(path.join(root, "public"))) {
  const relative = path.relative(path.join(root, "public"), file).replaceAll("\\", "/");
  if (/^(offline-build\/|offline-manifest\.json$|sw\.js$)/.test(relative)) continue;
  await add(file, `/${relative}`);
}
for (const file of await files(path.join(root, ".next/static"))) {
  if (file.endsWith(".map")) continue;
  await add(file, `/_next/static/${path.relative(path.join(root, ".next/static"), file).replaceAll("\\", "/")}`);
}
const appRoot = path.join(root, ".next/server/app");
for (const file of await files(appRoot)) {
  if (!file.endsWith(".body")) continue;
  const relative = path.relative(appRoot, file).replaceAll("\\", "/").slice(0, -5);
  if (!/\.(png|ico|svg|jpg|webp)$/.test(relative)) continue;
  await add(file, `/${relative}`);
}
for (const file of await files(appRoot)) {
  const relative = path.relative(appRoot, file).replaceAll("\\", "/");
  if (!relative.endsWith(".html") || relative.startsWith("_")) continue;
  const route = relative === "index.html" ? "/" : `/${relative.slice(0, -5)}`;
  const target = path.join(destination, relative);
  await mkdir(path.dirname(target), { recursive: true });
  await copyFile(file, target);
  await add(target, `${prefix}/${relative}`, route, "page");
  const rsc = file.slice(0, -5) + ".rsc";
  const rscTarget = target.slice(0, -5) + ".rsc";
  await copyFile(rsc, rscTarget);
  await add(rscTarget, `${prefix}/${relative.slice(0, -5)}.rsc`, `${prefix}/${relative.slice(0, -5)}.rsc`, "rsc");
  routes[route] = { rsc: `${prefix}/${relative.slice(0, -5)}.rsc`, segments: {} };
  const segments = file.slice(0, -5) + ".segments";
  for (const segment of await files(segments)) {
    const name = path.relative(segments, segment).replaceAll("\\", "/");
    const url = `${prefix}/${relative.slice(0, -5)}.segments/${name}`;
    const output = path.join(root, "public", url);
    await mkdir(path.dirname(output), { recursive: true });
    await copyFile(segment, output);
    await add(output, url, url, "rsc");
    routes[route].segments[`/${name.replace(/\.segment\.rsc$/, "")}`] = url;
  }
}
const fontCSS = [];
for (const file of await files(path.join(root, ".next/static"))) {
  if (!file.endsWith(".css")) continue;
  const css = await readFile(file, "utf8");
  fontCSS.push(...(css.match(/@font-face\{[^}]+\}/g) || []));
}
const fallback = (await readFile(path.join(root, "public/offline.html"), "utf8")).replace("</style>", `${fontCSS.join("").replaceAll("../media/", "/_next/static/media/")}</style>`);
await writeFile(path.join(destination, "offline.html"), fallback);
const fallbackResource = resources.find(item => item.key === "/offline.html");
fallbackResource.url = `${prefix}/offline.html`;
fallbackResource.bytes = Buffer.byteLength(fallback);
const manifest = { version, bytes: resources.reduce((sum, item) => sum + item.bytes, 0), resources, routes };
await writeFile(path.join(root, "public/offline-manifest.json"), JSON.stringify(manifest));
await writeFile(path.join(root, "public/sw.js"), `/* Generated by build-offline.mjs; do not edit. */\nself.OFFLINE_MANIFEST=${JSON.stringify(manifest)};\nimportScripts('/offline-worker.js');\n`);
console.log(`Offline copy: ${resources.length} resources, ${(manifest.bytes / 1048576).toFixed(2)} MiB, ${Object.keys(routes).length} routes, build ${version}`);

import json, re, sys
from pathlib import Path
import pdfplumber
import pypdfium2 as pdfium

root = Path(__file__).resolve().parents[2]
target = root / 'docs' / 'qa' / 'school-priority'
expectations = json.loads((target / 'pdf-expectations.json').read_text(encoding='utf-8'))
results = []
for row in expectations:
    path = target / (row['name'] + '.pdf')
    pages = []
    with pdfplumber.open(path) as pdf:
        full = ' '.join(page.extract_text() or '' for page in pdf.pages)
        normalized = re.sub(r'\s+', ' ', full)
        for index, page in enumerate(pdf.pages):
            words = page.extract_words()
            footer = page.search('Ginawa ng CAREER COMPASS:' if row['language'] == 'fil' else 'Generated by CAREER COMPASS:')[0]
            body_bottom = max(word['bottom'] for word in words if word['top'] < footer['top'] - 1)
            text = page.extract_text()
            page_label = f'Pahina {index+1} sa {len(pdf.pages)}' if row['language'] == 'fil' else f'Page {index+1} of {len(pdf.pages)}'
            checks = {
                'date_on_every_page': row['date'] in text,
                'page_number': page_label in text,
                'footer_separate_from_content': body_bottom + 3 < footer['top'],
                'footer_inside_page': max(word['bottom'] for word in words) < page.height - 5,
            }
            pages.append({'page': index+1, 'checks': checks, 'contentBottomPt': body_bottom, 'footerTopPt': footer['top']})
        brand = pdf.pages[0].search('CAREER COMPASS')[0]
        checks = {
            'one_or_two_pages': 1 <= len(pdf.pages) <= 2,
            'centered_brand': abs((brand['x0'] + brand['x1']) / 2 - pdf.pages[0].width / 2) < 2,
            'all_five_names': all(name in normalized for name in row['courses']),
            'no_stale_date': 'January 1, 1990' not in full,
            'no_percent_or_numeric_scores': not re.search(r'%|\b\d+\s*(?:points?|scores?|puntos|iskor)\b', full, re.I),
            'accented_name': 'QA Niño Áéíóú Ñü' in normalized,
            'no_images': all(not page.images for page in pdf.pages),
        }
        if row['name'].startswith('multi-'):
            checks['natural_multi_page_fixture'] = len(pdf.pages) == 2
        doc = pdfium.PdfDocument(path)
        for index in range(len(doc)):
            doc[index].render(scale=1.2).to_pil().save(target / f'{row["name"]}-{index+1}.png')
        (target / f'{row["name"]}.txt').write_text(full, encoding='utf-8')
        results.append({'name': row['name'], 'checks': checks, 'pages': pages, 'pass': all(checks.values()) and all(all(page['checks'].values()) for page in pages)})
(target / 'pdf-checks.json').write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps(results, ensure_ascii=False))
sys.exit(0 if all(row['pass'] for row in results) else 1)
